func TestGenerateStateMachineDocs(t *testing.T) {
	markdownMap, err := GenerateStateMachineDocs(context.Background())
	require.NoError(t, err)
	assert.NotNil(t, markdownMap)

	for pageName, markdown := range markdownMap {
		b, err := os.ReadFile(pageName)
		assert.NoError(t, err)
		assert.Equal(t, string(b), string(markdown), "The config reference docs generated by the code did not match the docs files in git for page: '%s' Did you forget to run `gradle generateDocs`?", pageName)
	}
}

func TestResolveCompositeLit(t *testing.T) {
	f, err := parser.ParseFile(token.NewFileSet(), "src.go", `package p
var direct = T{}
var viaVar = direct
func ctor() T { return T{} }
var viaCall = ctor()
func multi() T { x := T{}; return x }
var viaMulti = multi()
func noReturn() T { panic(1) }
var viaNoReturn = noReturn()
var viaSelector = pkg.Ctor()
var viaMethod = t.ctor()
var viaUnknownVar = unknown
var viaUnknownFunc = unknown()
var notLit = 1
`, 0)
	require.NoError(t, err)
	decls := &packageDecls{vars: make(map[string]ast.Expr), funcs: make(map[string]*ast.FuncDecl)}
	decls.add(f)

	for name, resolves := range map[string]bool{
		"direct":         true,
		"viaVar":         true,
		"viaCall":        true,
		"viaMulti":       false,
		"viaNoReturn":    false,
		"viaSelector":    false,
		"viaMethod":      false,
		"viaUnknownVar":  false,
		"viaUnknownFunc": false,
		"notLit":         false,
	} {
		_, ok := decls.resolveCompositeLit(decls.vars[name])
		assert.Equal(t, resolves, ok, name)
	}
}

func TestParseFile_PackageParseError(t *testing.T) {
	dir := t.TempDir()
	smPath := filepath.Join(dir, "state_machine.go")
	require.NoError(t, os.WriteFile(smPath, []byte("package p\n"), 0644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "broken.go"), []byte("package"), 0644))

	_, err := parseFile(smPath, smPath, "Test")
	assert.ErrorContains(t, err, "broken.go")
}

func TestParsePackageDecls_BadPattern(t *testing.T) {
	_, err := parsePackageDecls(token.NewFileSet(), "[")
	assert.ErrorIs(t, err, filepath.ErrBadPattern)
}
